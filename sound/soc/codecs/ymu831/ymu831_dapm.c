/*
 * YMU831 DAPM routing
 *
 * The CODEC's routing matrix (struct MCDRV_PATH_INFO) is described as DAPM
 * widgets: every destination channel is a mixer, or a mux where only one
 * source may be selected, with a switch per possible source. The core is
 * handed the routes that DAPM considers active, it takes care of the
 * register programming and the power sequencing.
 */

#include <linux/kernel.h>
#include <linux/slab.h>
#include <sound/soc.h>
#include <sound/soc-dapm.h>

#include "ymu831_priv.h"
#include "ymu831_dapm.h"

struct ymu831_route_bit {
	const char	*sink;
	const char	*source;
	size_t		offset;
	u32		on;
	u32		off;
};

#define YMU831_ROUTE_BIT(xsink, xsource, xmember, xon, xoff)		\
	{								\
		.sink = xsink,						\
		.source = xsource,					\
		.offset = offsetof(struct MCDRV_PATH_INFO, xmember),	\
		.on = xon,						\
		.off = xoff,						\
	}

static int ymu831_route_switch_put(struct snd_kcontrol *kcontrol,
				   struct snd_ctl_elem_value *ucontrol)
{
	int ret;

	ret = snd_soc_dapm_put_volsw(kcontrol, ucontrol);
	if (ret > 0)
		ymu831_dapm_update(snd_soc_dapm_kcontrol_to_component(kcontrol));

	return ret;
}

static int ymu831_route_mux_put(struct snd_kcontrol *kcontrol,
				struct snd_ctl_elem_value *ucontrol)
{
	int ret;

	ret = snd_soc_dapm_put_enum_double(kcontrol, ucontrol);
	if (ret > 0)
		ymu831_dapm_update(snd_soc_dapm_kcontrol_to_component(kcontrol));

	return ret;
}

#define YMU831_ROUTE_SWITCH(xname)					\
	SOC_SINGLE_EXT(xname, SND_SOC_NOPM, 0, 1, 0,			\
		       snd_soc_dapm_get_volsw, ymu831_route_switch_put)

#define YMU831_ROUTE_MUX(xname, xenum)					\
	SOC_DAPM_ENUM_EXT(xname, xenum, snd_soc_dapm_get_enum_double,	\
			  ymu831_route_mux_put)

